
using HarmonyLib;
using MarsarahTweaks.Managers;
using System;
using System.Collections.Generic;
using System.Reflection;
using System.Reflection.Emit;
using System.Runtime.CompilerServices;
using UnityEngine;

namespace MarsarahTweaks.Patches.Features
{
	internal class LessStandingBrazierSmoke
	{
		private static readonly LogManager log = new LogManager("Less Brazier Smoke", LogManager.LogLevel.Warning);

		private const float SmokeVisualScale = 0.5f;
		private const float SmokeEmissionInterval = 2f;
		private const float SmokeRiseSpeedMultiplier = 2f / 3f;

		private static readonly Dictionary<string, string> brazierPrefabs = new Dictionary<string, string>
		{
			// Vanilla
			{ "$piece_brazierfloor01", "piece_brazierfloor01" },
			{ "$piece_brazierfloor02", "piece_brazierfloor02" },
			{ "$piece_brazierceiling01", "piece_brazierceiling01" },

			// MarsarahBuildPieces
			{ "Green Standing Brazier", "piece_brazierfloor03" },
			{ "Silver Hanging Brazier", "piece_brazierceiling02" },
			{ "Blue-burning Silver Hanging Brazier", "piece_brazierceiling03" },
			{ "Green-burning Silver Hanging Brazier", "piece_brazierceiling04" }
		};

		private static readonly Dictionary<string, string> customBrazierSources = new Dictionary<string, string>
		{
			{ "piece_brazierfloor03", "piece_brazierfloor01" },
			{ "piece_brazierceiling02", "piece_brazierceiling01" },
			{ "piece_brazierceiling03", "piece_brazierceiling01" },
			{ "piece_brazierceiling04", "piece_brazierceiling01" }
		};

		private static readonly Dictionary<string, float> originalIntervals = new Dictionary<string, float>();

		// Weak references prevent retaining smoke objects after destruction.
		private static readonly ConditionalWeakTable<Smoke, object> brazierSmoke = new ConditionalWeakTable<Smoke, object>();

		private static bool isBrazierSpawning;
		private static bool loggedFirstSmoke;
		private static bool loggedFirstSlowSmoke;

		[HarmonyPatch(typeof(ZNetScene), "Awake")]
		private static class LessBrazierSmoke_AwakePatch
		{
			[HarmonyPriority(Priority.Last)]
			private static void Postfix(ZNetScene __instance)
			{
				if (__instance == null) return;
				if (ZNet.instance != null && ZNet.instance.IsDedicated()) return;

				UpdateSmoke(__instance);
			}
		}

		[HarmonyPatch(typeof(SmokeSpawner), "Spawn")]
		private static class SmokeSpawner_SpawnPatch
		{
			private static void Prefix(SmokeSpawner __instance, out bool __state)
			{
				__state = isBrazierSpawning;
				isBrazierSpawning = false;

				if (ZNet.instance != null && ZNet.instance.IsDedicated()) return;

				Piece piece = __instance.GetComponentInParent<Piece>();
				isBrazierSpawning = piece != null && TryGetBrazierPrefab(piece.m_name, out _);
			}

			private static void Postfix(bool __state)
			{
				isBrazierSpawning = __state;
			}
		}

		[HarmonyPatch(typeof(Smoke), "Awake")]
		private static class Smoke_AwakePatch
		{
			private static void Postfix(Smoke __instance)
			{
				if (!isBrazierSpawning) return;

				brazierSmoke.GetValue(__instance, _ => new object());

				if (!loggedFirstSmoke)
				{
					loggedFirstSmoke = true;
					log.Info("Successfully identified smoke generated by a brazier.");
				}

				if (!ConfigManager.LessStandingBrazierSmokeEnabled.Value) return;

				Vector3 velocity = __instance.m_vel;
				float originalSpeed = velocity.y;

				velocity.y *= SmokeRiseSpeedMultiplier;
				__instance.m_vel = velocity;

				if (!loggedFirstSlowSmoke)
				{
					loggedFirstSlowSmoke = true;
					log.Info($"Brazier smoke rising speed: {originalSpeed:0.###} -> {velocity.y:0.###}");
				}
			}
		}

		[HarmonyPatch(typeof(SmokeRenderer), "LateUpdate")]
		private static class SmokeRenderer_LateUpdatePatch
		{
			private static IEnumerable<CodeInstruction> Transpiler(IEnumerable<CodeInstruction> instructions)
			{
				List<CodeInstruction> codes = new List<CodeInstruction>(instructions);

				FieldInfo sizeField = AccessTools.Field(typeof(SmokeRenderer), "m_smokeBallSize");
				MethodInfo particleMethod = AccessTools.Method(typeof(Smoke), "GetParticleValues");
				MethodInfo scaleMethod = AccessTools.Method(typeof(LessStandingBrazierSmoke), nameof(AdjustVisualSize));

				if (sizeField == null || particleMethod == null || scaleMethod == null)
				{
					log.Warn("SmokeRenderer fields or methods not found. Visual size patch skipped.");
					return codes;
				}

				CodeInstruction smokeLocal = null;

				// Locate the Smoke instance used by the rendering loop.
				for (int i = 1; i < codes.Count; i++)
				{
					bool callsParticleMethod = (codes[i].opcode == OpCodes.Call || codes[i].opcode == OpCodes.Callvirt)
						&& Equals(codes[i].operand, particleMethod);

					if (callsParticleMethod && IsLoadLocal(codes[i - 1].opcode))
					{
						smokeLocal = new CodeInstruction(codes[i - 1].opcode, codes[i - 1].operand);
						break;
					}
				}

				if (smokeLocal == null)
				{
					log.Warn("Could not identify SmokeRenderer's smoke variable. Visual size patch skipped.");
					return codes;
				}

				int patched = 0;

				// Modify the size passed to the renderer for individual smoke puffs.
				for (int i = 0; i < codes.Count; i++)
				{
					if (codes[i].opcode != OpCodes.Ldfld || !Equals(codes[i].operand, sizeField)) continue;

					codes.Insert(i + 1, new CodeInstruction(smokeLocal.opcode, smokeLocal.operand));
					codes.Insert(i + 2, new CodeInstruction(OpCodes.Call, scaleMethod));

					i += 2;
					patched++;
				}

				if (patched == 0)
					log.Warn("SmokeRenderer size calculation not found. Visual size patch skipped.");
				else
					log.Info($"SmokeRenderer visual size patch applied at {patched} location(s).");

				return codes;
			}
		}

		[HarmonyPatch(typeof(SmokeSpawner), "Awake")]
		private static class SmokeSpawner_AwakePatch
		{
			private static void Postfix(SmokeSpawner __instance)
			{
				if (__instance == null) return;
				if (ZNet.instance != null && ZNet.instance.IsDedicated()) return;

				Piece piece = __instance.GetComponentInParent<Piece>();
				if (piece == null) return;

				if (!TryGetBrazierPrefab(piece.m_name, out string prefabName))
					return;

				if (!RememberOriginalInterval(__instance, prefabName))
					return;

				bool enabled = ConfigManager.LessStandingBrazierSmokeEnabled.Value;
				ApplySmokeInterval(__instance, prefabName, enabled);
			}
		}

		private static bool IsLoadLocal(OpCode opcode)
		{
			return opcode == OpCodes.Ldloc
				|| opcode == OpCodes.Ldloc_S
				|| opcode == OpCodes.Ldloc_0
				|| opcode == OpCodes.Ldloc_1
				|| opcode == OpCodes.Ldloc_2
				|| opcode == OpCodes.Ldloc_3;
		}

		private static float AdjustVisualSize(float originalSize, Smoke smoke)
		{
			if (ConfigManager.LessStandingBrazierSmokeEnabled == null ||
				!ConfigManager.LessStandingBrazierSmokeEnabled.Value)
				return originalSize;

			if (smoke != null && brazierSmoke.TryGetValue(smoke, out _))
				return originalSize * SmokeVisualScale;

			return originalSize;
		}

		private static bool TryGetBrazierPrefab(string pieceName, out string prefabName)
		{
			if (!brazierPrefabs.TryGetValue(pieceName, out prefabName))
				return false;

			if (customBrazierSources.ContainsKey(prefabName) &&
				!CompatibilityManager.MarsarahBuildPiecesInstalled)
				return false;

			return true;
		}

		private static bool RememberOriginalInterval(SmokeSpawner spawner, string prefabName)
		{
			if (originalIntervals.ContainsKey(prefabName))
				return true;

			float originalInterval;

			if (customBrazierSources.TryGetValue(prefabName, out string sourcePrefabName))
			{
				if (!originalIntervals.TryGetValue(sourcePrefabName, out originalInterval))
				{
					GameObject sourcePrefab = ZNetScene.instance?.GetPrefab(sourcePrefabName);
					SmokeSpawner sourceSpawner = sourcePrefab?.GetComponentInChildren<SmokeSpawner>(true);

					if (sourceSpawner == null)
						return false;

					originalInterval = sourceSpawner.m_interval;
					originalIntervals[sourcePrefabName] = originalInterval;
				}
			}
			else
			{
				originalInterval = spawner.m_interval;
			}

			originalIntervals[prefabName] = originalInterval;

			log.Info($"Backed up smoke interval for {prefabName}: {originalInterval:0.##}s");

			return true;
		}

		public static void UpdateSmoke(ZNetScene znScene)
		{
			if (znScene == null) return;
			if (ZNet.instance != null && ZNet.instance.IsDedicated()) return;

			bool enabled = ConfigManager.LessStandingBrazierSmokeEnabled.Value;
			bool buildPiecesInstalled = CompatibilityManager.MarsarahBuildPiecesInstalled;

			log.Info($"Less Brazier Smoke enabled: {enabled}");

			if (buildPiecesInstalled)
				log.Info("MarsarahBuildPieces detected. Custom brazier smoke support enabled.");

			// Update registered prefab intervals.
			foreach (var entry in brazierPrefabs)
			{
				string prefabName = entry.Value;
				bool isCustom = customBrazierSources.ContainsKey(prefabName);

				if (isCustom && !buildPiecesInstalled)
					continue;

				GameObject prefab = znScene.GetPrefab(prefabName);

				if (prefab == null)
				{
					if (isCustom)
						log.Info($"Custom brazier prefab not registered yet: {prefabName}");
					else
						log.Warn($"Could not find brazier prefab: {prefabName}");

					continue;
				}

				SmokeSpawner[] spawners = prefab.GetComponentsInChildren<SmokeSpawner>(true);

				if (spawners.Length == 0)
				{
					log.Warn($"No SmokeSpawner found on {prefabName}");
					continue;
				}

				foreach (SmokeSpawner spawner in spawners)
				{
					if (!RememberOriginalInterval(spawner, prefabName))
						continue;

					ApplySmokeInterval(spawner, prefabName, enabled);
				}
			}

			// Update already-placed braziers.
			foreach (SmokeSpawner spawner in UnityEngine.Object.FindObjectsByType<SmokeSpawner>(FindObjectsInactive.Include, FindObjectsSortMode.None))
			{
				Piece piece = spawner.GetComponentInParent<Piece>();
				if (piece == null) continue;

				if (!TryGetBrazierPrefab(piece.m_name, out string prefabName))
					continue;

				if (!RememberOriginalInterval(spawner, prefabName))
					continue;

				ApplySmokeInterval(spawner, prefabName, enabled);
			}
		}

		private static void ApplySmokeInterval(SmokeSpawner spawner, string prefabName, bool enabled)
		{
			float originalInterval = originalIntervals[prefabName];
			float targetInterval = enabled ? SmokeEmissionInterval : originalInterval;

			if (Mathf.Approximately(spawner.m_interval, targetInterval)) return;

			log.Info($"{prefabName}: Smoke interval {spawner.m_interval:0.##}s -> {targetInterval:0.##}s");

			spawner.m_interval = targetInterval;
		}
	}
}
