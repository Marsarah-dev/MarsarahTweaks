
using HarmonyLib;
using MarsarahTweaks.Managers;
using System;
using System.Collections.Generic;
using System.Reflection;
using System.Reflection.Emit;
using System.Runtime.CompilerServices;
using UnityEngine;

namespace MarsarahTweaks.Patches.Features
{
	internal class LessStandingBrazierSmoke
	{
		private static readonly LogManager log = new LogManager("Less Brazier Smoke", LogManager.LogLevel.Info);

		private const float SmokeVisualScale = 0.5f;

		private static readonly HashSet<string> brazierNames = new HashSet<string>
		{
			"$piece_brazierfloor01",
			"$piece_brazierfloor02",
			"$piece_brazierceiling01"
		};

		// Weak references prevent retaining smoke objects after destruction.
		private static readonly ConditionalWeakTable<Smoke, object> brazierSmoke = new ConditionalWeakTable<Smoke, object>();

		private static bool isBrazierSpawning;
		private static bool loggedFirstSmoke;

		[HarmonyPatch(typeof(ZNetScene), "Awake")]
		private static class LessBrazierSmoke_AwakePatch
		{
			private static void Postfix(ZNetScene __instance)
			{
				if (__instance == null) return;
				if (ZNet.instance != null && ZNet.instance.IsDedicated()) return;

				UpdateSmoke(__instance);
			}
		}

		[HarmonyPatch(typeof(SmokeSpawner), "Spawn")]
		private static class SmokeSpawner_SpawnPatch
		{
			private static void Prefix(SmokeSpawner __instance, out bool __state)
			{
				__state = isBrazierSpawning;
				isBrazierSpawning = false;

				if (ZNet.instance != null && ZNet.instance.IsDedicated()) return;

				Piece piece = __instance.GetComponentInParent<Piece>();
				isBrazierSpawning = piece != null && brazierNames.Contains(piece.m_name);
			}

			private static void Postfix(bool __state)
			{
				isBrazierSpawning = __state;
			}
		}

		[HarmonyPatch(typeof(Smoke), "Awake")]
		private static class Smoke_AwakePatch
		{
			private static void Postfix(Smoke __instance)
			{
				if (!isBrazierSpawning) return;

				brazierSmoke.GetValue(__instance, _ => new object());

				if (!loggedFirstSmoke)
				{
					loggedFirstSmoke = true;
					log.Info("Successfully identified smoke generated by a brazier.");
				}
			}
		}

		[HarmonyPatch(typeof(SmokeRenderer), "LateUpdate")]
		private static class SmokeRenderer_LateUpdatePatch
		{
			private static IEnumerable<CodeInstruction> Transpiler(IEnumerable<CodeInstruction> instructions)
			{
				List<CodeInstruction> codes = new List<CodeInstruction>(instructions);

				FieldInfo sizeField = AccessTools.Field(typeof(SmokeRenderer), "m_smokeBallSize");
				MethodInfo particleMethod = AccessTools.Method(typeof(Smoke), "GetParticleValues");
				MethodInfo scaleMethod = AccessTools.Method(typeof(LessStandingBrazierSmoke), nameof(AdjustVisualSize));

				if (sizeField == null || particleMethod == null || scaleMethod == null)
				{
					log.Warn("SmokeRenderer fields or methods not found. Visual size patch skipped.");
					return codes;
				}

				CodeInstruction smokeLocal = null;

				// Locate the Smoke instance used by the rendering loop.
				for (int i = 1; i < codes.Count; i++)
				{
					bool callsParticleMethod = (codes[i].opcode == OpCodes.Call || codes[i].opcode == OpCodes.Callvirt)
						&& Equals(codes[i].operand, particleMethod);

					if (callsParticleMethod && IsLoadLocal(codes[i - 1].opcode))
					{
						smokeLocal = new CodeInstruction(codes[i - 1].opcode, codes[i - 1].operand);
						break;
					}
				}

				if (smokeLocal == null)
				{
					log.Warn("Could not identify SmokeRenderer's smoke variable. Visual size patch skipped.");
					return codes;
				}

				int patched = 0;

				// Modify the size passed to the renderer for individual smoke puffs.
				for (int i = 0; i < codes.Count; i++)
				{
					if (codes[i].opcode != OpCodes.Ldfld || !Equals(codes[i].operand, sizeField)) continue;

					codes.Insert(i + 1, new CodeInstruction(smokeLocal.opcode, smokeLocal.operand));
					codes.Insert(i + 2, new CodeInstruction(OpCodes.Call, scaleMethod));

					i += 2;
					patched++;
				}

				if (patched == 0)
					log.Warn("SmokeRenderer size calculation not found. Visual size patch skipped.");
				else
					log.Info($"SmokeRenderer visual size patch applied at {patched} location(s).");

				return codes;
			}
		}

		private static bool IsLoadLocal(OpCode opcode)
		{
			return opcode == OpCodes.Ldloc
				|| opcode == OpCodes.Ldloc_S
				|| opcode == OpCodes.Ldloc_0
				|| opcode == OpCodes.Ldloc_1
				|| opcode == OpCodes.Ldloc_2
				|| opcode == OpCodes.Ldloc_3;
		}

		private static float AdjustVisualSize(float originalSize, Smoke smoke)
		{
			if (ConfigManager.LessStandingBrazierSmokeEnabled == null ||
				!ConfigManager.LessStandingBrazierSmokeEnabled.Value)
				return originalSize;

			if (smoke != null && brazierSmoke.TryGetValue(smoke, out _))
				return originalSize * SmokeVisualScale;

			return originalSize;
		}

		public static void UpdateSmoke(ZNetScene znScene)
		{
			if (znScene == null) return;
			if (ZNet.instance != null && ZNet.instance.IsDedicated()) return;

			log.Info($"Less Brazier Smoke enabled: {ConfigManager.LessStandingBrazierSmokeEnabled.Value}");
		}
	}
}
